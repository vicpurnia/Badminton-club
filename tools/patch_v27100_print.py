#!/usr/bin/env python3
"""v27.9.10: strict Classic A4 landscape Android printing & immutable spool.

Run after the v27.9.9 independent PDF-share snapshot integration.
No change to Classic PDF pixel dimensions, Room schema, payments or signing.
"""
from pathlib import Path
root=Path("app/src/main/java/com/vinayak/badminton/nativepreview")
p=root/"MainActivity.java"
s=p.read_text(encoding="utf-8")
def once(old,new):
 global s
 if s.count(old)!=1:
  raise AssertionError(f"Classic print source anchor changed ({s.count(old)}): {old[:100]}")
 s=s.replace(old,new,1)

once('''   final File source=ClassicLedgerV231.master(this,database.dao(),selectedMonth);
   verifyClassicPdf(source);
   runOnUiThread''',
     '''   final File generated=ClassicLedgerV231.master(this,database.dao(),selectedMonth);
   verifyClassicPdf(generated);
   // Snapshot before Android print UI opens. The filename generated by older
   // PDF renderers can have millisecond granularity: a later render must never
   // modify the document currently being spooled by Android PrintManager.
   final PremiumV2799PdfShare.Share spool;
   try{
    spool=PremiumV2799PdfShare.snapshot(shareCacheDir(),generated);
   }catch(Exception ex){
    generated.delete();
    throw ex;
   }
   final File source=spool.file;
   runOnUiThread''')

once('''       if(current.getMediaSize()!=null&&current.getMediaSize().isPortrait()){
        callback.onLayoutFailed("Please select A4 landscape instead of portrait");
        return;
       }''',
     '''       // A landscape LETTER sheet is not A4. Require exact ISO A4
       // dimensions/identity rather than accepting every landscape size.
       PrintAttributes.MediaSize required=PrintAttributes.MediaSize.ISO_A4.asLandscape();
       PrintAttributes.MediaSize chosen=current==null?null:current.getMediaSize();
       try{
        PremiumV27100A4PrintGuard.requireExact(
         chosen==null?null:chosen.getId(),
         chosen==null?0:chosen.getWidthMils(),
         chosen==null?0:chosen.getHeightMils(),
         required.getId(),required.getWidthMils(),required.getHeightMils());
       }catch(IOException invalidPaper){
        callback.onLayoutFailed(invalidPaper.getMessage());
        return;
       }''')

once('''         byte[] buffer=new byte[16384];int count;
         while((count=input.read(buffer))!=-1){
          if(signal.isCanceled()){callback.onWriteCancelled();return;}
          output.write(buffer,0,count);
         }
         output.flush();
         callback.onWriteFinished(new PageRange[]{PageRange.ALL_PAGES});''',
     '''         byte[] buffer=new byte[16384];int count;
         long written=0;
         while((count=input.read(buffer))!=-1){
          if(signal.isCanceled()){callback.onWriteCancelled();return;}
          if(count<=0)continue;
          written=Math.addExact(written,count);
          output.write(buffer,0,count);
         }
         output.flush();
         PremiumV2799PdfShare.verify(spool);
         if(written!=spool.length)
          throw new IOException("A4 print spool content count changed during write");
         callback.onWriteFinished(new PageRange[]{PageRange.ALL_PAGES});''')

once('''      @Override public void onFinish(){source.delete();super.onFinish();}
     },attributes);
    }catch(Exception exception){
     source.delete();
     error(new IOException("Unable to start A4 landscape printing: "+exception.getMessage()));''',
     '''      @Override public void onFinish(){
       source.delete();
       generated.delete();
       super.onFinish();
      }
     },attributes);
    }catch(Exception exception){
     source.delete();
     generated.delete();
     error(new IOException("Unable to start A4 landscape printing: "+exception.getMessage()));''')

for required in ("PremiumV27100A4PrintGuard.requireExact",
                 "PremiumV2799PdfShare.snapshot(shareCacheDir(),generated)",
                 "PremiumV2799PdfShare.verify(spool)",
                 "generated.delete();"):
 if required not in s:raise AssertionError("Classic print contract missing "+required)
p.write_text(s,encoding="utf-8")
(root/"PremiumV27100A4PrintGuard.java").write_text(
 Path("src/premium/v27_9_10/PremiumV27100A4PrintGuard.java").read_text(encoding="utf-8"),
 encoding="utf-8")
print("PASS v27.9.10 strict ISO A4 landscape and independent SHA-pinned print spool")
